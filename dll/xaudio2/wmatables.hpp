struct XaWmaRateEntry
{
    UINT32 BitRate;
    UINT8 PacketFrames;
    UINT8 Bits;
    UINT16 Subframes;
    UINT32 Weighting;
    UINT32 Flags;
};

/* The encodings offered for one rate and channel count */
struct XaWmaRateGroup
{
    UINT32 Rate;
    UINT16 Channels;
    UINT16 Count;
    const XaWmaRateEntry* Entries;
};

