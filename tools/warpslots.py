"""
Writes dll/d3d10warp/slots.inl: every field of the newest device and DXGI function tables, so the
driver can give each one a typed placeholder before it fills in the real entry points.

    cl /P /EP <file including d3d10umddi.h>   (gives a preprocessed .i)
    python tools/warpslots.py <preprocessed .i> > dll/d3d10warp/slots.inl
"""
import re
import sys


def fields(source, name):
    match = re.search(r'typedef\s+struct\s+%s\s*\{(.*?)\}\s*%s\s*[;,]' % (name, name), source, re.S)
    if not match:
        raise SystemExit('no struct %s' % name)
    body = match.group(1)
    if 'DXGI' in name:
        return re.findall(r'\*\s*(pfn\w+)\s*\)', body)
    return re.findall(r'(\w+)\s*;', body)


def main():
    source = open(sys.argv[1], encoding='latin1').read()
    print('/* Generated by tools/warpslots.py from the SDK headers */')
    print('#ifdef RX_DEVICE_SLOT')
    for field in fields(source, 'D3DWDDM2_6DDI_DEVICEFUNCS'):
        macro = 'RX_DEVICE_SIZE_SLOT' if field.startswith('pfnCalcPrivate') else 'RX_DEVICE_SLOT'
        print('%s(%s)' % (macro, field))
    print('#endif')
    print('#ifdef RX_DXGI_SLOT')
    for field in fields(source, 'DXGI1_6_1_DDI_BASE_FUNCTIONS'):
        print('RX_DXGI_SLOT(%s)' % field)
    print('#endif')


if __name__ == '__main__':
    main()
