"""
Writes dll/d3d10warp/srgbtable.inl: the 256 linear values that eight bit sRGB codes read as,
taken from a reference WARP binary so sampling matches it to the bit.

    python tools/warpsrgb.py <d3d10warp.dll> <table VA> > dll/d3d10warp/srgbtable.inl
"""
import struct
import sys

import pefile

BASE = 0x180000000


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    table = int(sys.argv[2], 16)
    data = pe.get_data(table - BASE, 256 * 4)
    values = struct.unpack('<256I', data)

    if values[0] != 0 or values[255] != 0x3F800000:
        raise SystemExit('that address does not hold the sRGB table')

    print('/* Generated by tools/warpsrgb.py: linear value of each eight bit sRGB code, as float bits */')
    for row in range(0, 256, 8):
        print('    ' + ', '.join('0x%08X' % value for value in values[row:row + 8]) + ',')


if __name__ == '__main__':
    main()
