"""
Writes dll/d3d10warp/dithertable.inl: the alpha to coverage dither of each pixel in an 8x8 tile,
taken from a reference WARP binary where it is stored per 2x2 quad, four lanes each.

    python tools/warpdither.py <d3d10warp.dll> <table VA> > dll/d3d10warp/dithertable.inl
"""
import struct
import sys

import pefile

BASE = 0x180000000


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    table = int(sys.argv[2], 16)
    quads = struct.unpack('<64f', pe.get_data(table - BASE, 64 * 4))

    if any(not (-1.0 < value < 1.0) for value in quads):
        raise SystemExit('that address does not hold the dither table')

    print('/* Generated by tools/warpdither.py: alpha to coverage dither for pixel (x & 7, y & 7), row by row */')
    for y in range(8):
        row = []
        for x in range(8):
            index = (((y >> 1) & 3) * 4 + ((x >> 1) & 3)) * 4 + (x & 1) + 2 * (y & 1)
            row.append('%.8ff' % quads[index])
        print('    ' + ', '.join(row) + ',')


if __name__ == '__main__':
    main()
