"""
Writes dll/d3d10warp/bptctables.inl: the BC6H and BC7 partition shapes, anchor positions,
BC6H header bit layouts and BC6H mode descriptions, located in a reference WARP binary
by their known leading bytes.

    python tools/warpbptc.py <d3d10warp.dll> > dll/d3d10warp/bptctables.inl
"""
import struct
import sys

import pefile


def find(data, pattern, what):
    at = data.find(pattern)
    if at < 0 or data.find(pattern, at + 1) >= 0:
        raise SystemExit('could not find exactly one ' + what)
    return at


def rows(values, width):
    for start in range(0, len(values), width):
        yield ', '.join(str(v) for v in values[start:start + width])


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    data = b''.join(section.get_data() for section in pe.sections)

    # Two subset shapes start right after 64 one subset shapes of all zeros
    second = bytes([0, 0, 1, 1] * 4 + [0, 0, 0, 1] * 4)
    at = find(data, bytes(1024) + second, 'partition table')
    partition = data[at:at + 3 * 64 * 16]

    # Anchors: none for one subset, then the second subset's anchor at 15 for the first shapes
    at = find(data, bytes(64 * 3) + bytes([0, 15, 0] * 17) + bytes([0, 2, 0]), 'anchor table')
    anchor = data[at:at + 3 * 64 * 3]

    # BC6H header layouts: field and bit for each of the 82 header bits of 14 modes
    at = find(data, bytes([1, 0, 1, 1, 9, 4, 13, 4, 14, 4, 3, 0, 3, 1, 3, 2]), 'BC6H layout')
    layout = data[at:at + 14 * 82 * 2]

    # BC6H modes: mode, partitions, transformed, index bits, then endpoint precisions per region
    at = find(data, bytes([0, 1, 1, 3, 10, 10, 10, 0, 5, 5, 5, 0, 5, 5, 5, 0, 5, 5, 5, 0]), 'BC6H modes')
    modes = data[at:at + 14 * 20]

    at = find(data, struct.pack('<8i', 0, 1, 2, 10, -1, -1, 3, 11), 'BC6H mode index')
    index = struct.unpack_from('<32i', data, at)

    print('/* Generated by tools/warpbptc.py from a reference WARP binary */')
    print('static const UINT8 RxBptcShape[3][64][16] =\n{')
    for line in rows(partition, 16):
        print('    ' + line + ',')
    print('};\n')
    print('static const UINT8 RxBptcAnchor[3][64][3] =\n{')
    for line in rows(anchor, 24):
        print('    ' + line + ',')
    print('};\n')
    print('/* Field (0 unused, 1 mode, 2 shape, 3 to 14 endpoint channels) and bit for every header bit */')
    print('static const UINT8 RxBc6hLayout[14][82][2] =\n{')
    for line in rows(layout, 20):
        print('    ' + line + ',')
    print('};\n')
    print('/* Mode bits, partitions, transformed, index bits, then rgba precision of each endpoint pair */')
    print('static const UINT8 RxBc6hModes[14][20] =\n{')
    for line in rows(modes, 20):
        print('    ' + line + ',')
    print('};\n')
    print('static const INT8 RxBc6hModeIndex[32] =\n{')
    for line in rows(index, 16):
        print('    ' + line + ',')
    print('};')


if __name__ == '__main__':
    main()
