import argparse
import re
import sys

HEADER_TEMPLATE = """/*
 * PROJECT:     {project}
 * LICENSE:     MIT (https://spdx.org/licenses/MIT)
 * PURPOSE:     {purpose}
 * COPYRIGHT:   Copyright 2026 Justin Miller <justinmiller100@gmail.com>
 *
 * Generated by tools/gencom.py from {header}. Do not edit.
 */
"""


def read_macro_interface(text, name):
    # dwrite.h and d2d1.h: interface X_DECLARE_INTERFACE("iid") Name : public Base { STDMETHOD(...) PURE; };
    match = re.search(r"\binterface\s+\w+\(\"[^\"]*\"\)\s+" + re.escape(name) + r"\s*:\s*public\s+\w+\s*\{(.*?)\n\};", text, re.S)
    if match is None:
        return None

    body = re.sub(r"//[^\n]*", "", match.group(1))
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    methods = []
    pattern = r"STDMETHOD(?:_\(\s*(.+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\((.*?)\)\s*(?:CONST\s*)?PURE\s*;"
    for method in re.finditer(pattern, body, re.S):
        result, typed_name, plain_name, params = method.groups()
        if plain_name is not None:
            methods.append(("HRESULT", plain_name, split_params(params)))
        else:
            methods.append((" ".join(result.split()), typed_name, split_params(params)))
    return methods


def read_interface(text, name):
    methods = read_macro_interface(text, name)
    if methods is not None:
        return methods

    match = re.search(r"\n\s*" + re.escape(name) + r"\s*:\s*public\s+\w+\s*\{\s*public:(.*?)\n\s*\};", text, re.S)
    if match is None:
        sys.exit("interface %s not found" % name)

    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)
    # Struct returning methods carry a second, non MSVC declaration; keep the MSVC one
    body = re.sub(r"#else.*?#endif", "", body, flags=re.S)
    body = re.sub(r"#if[^\n]*", "", body)
    methods = []
    for method in re.finditer(r"virtual\s+(.*?)\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*(const\s*)?=\s*0\s*;", body, re.S):
        result, method_name, params, _ = method.groups()
        methods.append((result.strip(), method_name, split_params(params)))
    return methods


def split_params(params):
    params = " ".join(params.split())
    if params in ("", "void"):
        return []

    parts = []
    depth = 0
    current = ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current)
            current = ""
            continue
        current += ch
    parts.append(current)
    return [tidy_param(part) for part in parts]


def tidy_param(param):
    param = " ".join(param.split())
    param = re.sub(r"\(\s+", "(", param)
    param = re.sub(r"\s+\)", ")", param)
    param = re.sub(r"\s+\*", "*", param)
    param = re.sub(r"(?<=[\w*])\*(?=[A-Za-z_])", "* ", param)
    return param


def map_result(result):
    return "VOID" if result == "void" else result


def signature(method, prefix, indent, terminator):
    result, name, params = method
    lines = [indent + map_result(result), indent + "STDMETHODCALLTYPE"]
    if not params:
        lines.append("%s%s%s(VOID)%s" % (indent, prefix, name, terminator))
        return lines

    lines.append("%s%s%s(" % (indent, prefix, name))
    # Default arguments belong on the declaration only
    if prefix:
        params = [re.sub(r"\s*=\s*[^,]+$", "", param) for param in params]
    for index, param in enumerate(params):
        tail = "," if index + 1 < len(params) else ")" + terminator
        lines.append(indent + "    " + param + tail)
    return lines


def stub_body(result):
    if result == "void":
        return ["{", "    RX_UNIMPLEMENTED();", "}"]
    if result == "HRESULT":
        return ["{", "    RX_UNIMPLEMENTED();", "    return E_NOTIMPL;", "}"]
    return ["{", "    RX_UNIMPLEMENTED();", "    return {};", "}"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", action="append", required=True)
    parser.add_argument("--interface", action="append", required=True)
    parser.add_argument("--class", dest="class_name", required=True)
    parser.add_argument("--decl", required=True)
    parser.add_argument("--stubs", required=True)
    parser.add_argument("--implemented", default="")
    parser.add_argument("--include", default="precomp.hpp")
    parser.add_argument("--purpose", default="COM method declarations")
    parser.add_argument("--project", default="ReactX Direct3D 11 runtime")
    args = parser.parse_args()

    text = ""
    for header in args.header:
        with open(header, encoding="utf-8", errors="ignore") as handle:
            text += handle.read() + "\n"

    implemented = {name for name in args.implemented.split(",") if name}
    header_name = ", ".join(header.replace("\\", "/").split("/")[-1] for header in args.header)

    methods = []
    for interface in args.interface:
        methods.extend(read_interface(text, interface))

    seen = {method[1] for method in methods}
    missing = implemented - seen
    if missing:
        sys.exit("unknown --implemented names: " + ", ".join(sorted(missing)))

    decl = [HEADER_TEMPLATE.format(project=args.project, purpose=args.purpose + " (declarations)", header=header_name)]
    for method in methods:
        decl.extend(signature(method, "", "    ", " override;"))
        decl.append("")

    stubs = [HEADER_TEMPLATE.format(project=args.project, purpose=args.purpose + " (stubs)", header=header_name)]
    stubs.append('#include "%s"' % args.include)
    stubs.append("")
    for method in methods:
        if method[1] in implemented:
            continue
        stubs.extend(signature(method, args.class_name + "::", "", ""))
        stubs.extend(stub_body(method[0]))
        stubs.append("")

    with open(args.decl, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(decl).rstrip() + "\n")
    with open(args.stubs, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(stubs).rstrip() + "\n")

    print("%s: %d methods, %d stubbed" % (args.class_name, len(methods), len(methods) - len(implemented & seen)))


if __name__ == "__main__":
    main()
