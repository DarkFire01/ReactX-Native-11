"""
Writes dll/d3d10warp/formatcaps.inl: per DXGI format, the base DDI format support bits and
whether 2, 4, 8 and 16 samples are offered, read from a reference WARP binary.

    python tools/warpformats.py <d3d10warp.dll> <table VA> > dll/d3d10warp/formatcaps.inl

The table is plain data; the device code applies the version dependent extras on top.
"""
import struct
import sys

import pefile

BASE = 0x180000000
COUNT = 192
STRIDE = 32


def field(value, shift):
    """Two bit capability fields; all ones means not supported."""
    return (value >> shift) & 3 != 3


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    table = int(sys.argv[2], 16)

    def read(va, size):
        return pe.get_data(va - BASE, size)

    rows = []
    for index in range(COUNT):
        entry = read(table + index * STRIDE, STRIDE)
        family = struct.unpack_from('<Q', entry, 8)[0]
        first, second = struct.unpack_from('<II', entry, 24)
        rows.append((family, first, second))

    def caps(index):
        family, first, second = rows[index]
        if not first & 0x100:
            return None
        bits = 0
        if field(first, 24):
            bits |= 0x1          # shader sample
        if field(first, 28):
            bits |= 0x2          # render target
        if field(first, 30):
            bits |= 0x4          # blendable
        if field(second, 2):
            bits |= 0x8          # multisample render target
        if field(second, 4):
            bits |= 0x10         # multisample load
        if field(second, 8):
            bits |= 0x100        # vertex buffer
        if field(second, 10):
            bits |= 0x400        # typed buffer
        if field(second, 6):
            bits |= 0x20200      # typed UAV writes and reads
        if field(first, 26):
            bits |= 0x4000       # gather
        return bits

    def displayable(index):
        if index <= 87:
            return index == 87 or (0 <= index - 10 <= 0x39 and (0x200000000044001 >> (index - 10)) & 1)
        return index in (103, 104, 107)

    def multisample(index):
        family, first, second = rows[index]
        if field(second, 2):
            return True
        # A typeless format counts when one of its family members renders to multisample targets
        if (first >> 8) & 3 == 2 and not field(first, 28) and not field(second, 0) and family:
            offset = 0
            while True:
                member = struct.unpack('<I', read(family + offset, 4))[0]
                if member == 0:
                    break
                if member != index:
                    other = member if member < COUNT else 0
                    if field(rows[other][2], 2):
                        return True
                offset += 4
        return False

    print('/* Generated by tools/warpformats.py: { valid, support bits, displayable, multisample } per DXGI format */')
    for index in range(COUNT):
        bits = caps(index)
        if bits is None:
            print('    { FALSE, 0x00000000, FALSE, FALSE }, /* %d */' % index)
            continue
        print('    { TRUE, 0x%08X, %s, %s }, /* %d */' % (bits, 'TRUE' if displayable(index) else 'FALSE',
                                                       'TRUE' if multisample(index) else 'FALSE', index))


if __name__ == '__main__':
    main()
